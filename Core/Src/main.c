void StartMonitorTask(void const * argument)
{
  /* USER CODE BEGIN StartMonitorTask */
  TickType_t last_wake = xTaskGetTickCount();
  uint8_t oled_divider = 0U;

  (void)argument;

  for (;;)
  {
    VOFA_Process();

    oled_divider++;
    if (oled_divider >= 2U)
    {
      oled_divider = 0U;
      OLED_ShowVoltage(Potentiometer_Voltage);
      OLED_ShowSpeed(2, Motor_TargetSpeed);
      OLED_ShowSpeed(3, Motor_ActualSpeed);
      OLED_ShowString(4, 8, (motor_enabled != 0U) ? "RUN " : "STOP");
    }

    vTaskDelayUntil(&last_wake, pdMS_TO_TICKS(MONITOR_TASK_PERIOD_MS));
  }
  /* USER CODE END StartMonitorTask */
}

